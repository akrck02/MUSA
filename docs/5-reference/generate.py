#!/usr/bin/env python3
"""Writes the reference in docs/5-reference from the Go doc comments and the errors.go files.

Run from the repository's root after changing a public name or an error code:

    python3 docs/5-reference/generate.py

Each package gets a page: its comment, then every public name with the first sentence of its
comment. One more page lists every error code. The doc comments are the source of truth: improve
them, not the generated pages.
"""
import glob
import re
import subprocess

MODULE = "github.com/Itros97/MUSA"

# The packages in the order of the code map, from the base up.
PACKAGES = ["money", "calendar", "storage", "look", "cash", "customers", "catalogue", "sales",
            "events", "projects", "stand", "demo", "app"]

GENERATED = "<!-- Generated by docs/5-reference/generate.py from the doc comments: do not edit. -->"


def go_doc(*arguments):
    return subprocess.run(["go", "doc", *arguments], capture_output=True, text=True, check=True).stdout


def first_sentence(text):
    text = " ".join(text.split())
    match = re.match(r"(.+?\.)(\s|$)", text)
    return (match.group(1) if match else text).replace("|", "\\|")


def package_comment(package):
    """The package's comment: what go doc prints between the package line and the first name."""
    lines = go_doc(f"{MODULE}/{package}").split("\n")[1:]
    comment = []
    for line in lines:
        if re.match(r"(func|type|const|var) ", line):
            break
        comment.append(line.strip())
    return " ".join(" ".join(comment).split())


def public_names(package):
    """Every public name of a package with the first sentence of its comment, as go doc -short gives the list."""
    rows = []
    for declaration in go_doc("-short", f"{MODULE}/{package}").strip().split("\n"):
        name = re.match(r"\s*(?:func|type|const|var)\s+(?:\([^)]*\)\s*)?(\w+)", declaration)
        if not name:
            continue
        symbol = name.group(1)
        receiver = re.match(r"\s*func\s+\(\w+\s+\*?(\w+)\)", declaration)
        target = f"{receiver.group(1)}.{symbol}" if receiver else symbol
        comment = go_doc(f"{MODULE}/{package}", target).split("\n")
        text = " ".join(line.strip() for line in comment if line.startswith("    "))
        rows.append((declaration.strip(), first_sentence(text)))
    return rows


def write_package(index, package):
    page = f"docs/5-reference/{index}-{package.replace('/', '-')}.md"
    with open(page, "w") as file:
        file.write(f"# {package}\n---\n\n{GENERATED}\n\n{package_comment(package)}\n\n")
        file.write("| Name | What it is |\n|---|---|\n")
        for declaration, sentence in public_names(package):
            file.write(f"| `{declaration.replace('|', '\\|')}` | {sentence} |\n")
    return page


def artist_words(folder):
    """What the artist reads for each code, by the code's Go name, from the package's words.go."""
    try:
        source = open(f"{folder}/words.go").read()
    except FileNotFoundError:
        return {}
    return {name: words for name, words in re.findall(r'(Code\w+):\s*"([^"]*)"', source)}


def write_codes(index):
    rows = []
    for path in sorted(glob.glob("*/errors.go")):
        folder = path.split("/")[0]
        words = artist_words(folder)
        for name, code in re.findall(r'(Code\w+)\s+Code\s*=\s*"([\w.-]+)"', open(path).read()):
            rows.append((code, words.get(name, "")))
    with open(f"docs/5-reference/{index}-error-codes.md", "w") as file:
        file.write(f"# Error codes\n---\n\n{GENERATED}\n\n")
        file.write("Every code MUSA's packages return. Problems are what the artist can fix, and the "
                   "app says them in Spanish; failures have no words, because the artist cannot fix "
                   "them. Check codes with `errors.As` or the package's helper, never by the error's "
                   "text.\n\n| Code | What the artist reads |\n|---|---|\n")
        for code, meaning in rows:
            file.write(f"| `{code}` | {meaning} |\n")


def main():
    for index, package in enumerate(PACKAGES, start=1):
        write_package(index, package)
    write_codes(len(PACKAGES) + 1)


main()
